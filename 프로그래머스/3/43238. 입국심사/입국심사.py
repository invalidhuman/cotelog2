def solution(n, times):
    
    # 제한시간 범위 추측
    # 1명 <= x <= 10억명 이하
    # 1분 <= x <= 10억분 이하
    # 1명 <= 심사관 수 <= 100,000명 이하
    
    # 상한, 하한
    start,end = 1,min(times) * n
    # 모든 사람이 가장 빠른 심사관한테만 간다고 했을 때, 
    # 적어도 분배를 해서 간다면 이거보단 빠를 것
    
    while (start <= end):
        mid = (start + end)// 2 
        
        cnt = 0
        
        # 중간값이 제한시간이라고 생각하고, 그 동안 최대 몇 명이나 처리할 수 있을 지 추측
        for time in times:
            # 최대 인원 세기 : 제한 시간 / 그 심사관의 한 명당 처리 시간
            cnt += mid // time 
            
        # 반복문이 끝나면 cnt는 mid시간 동안 times의 심사관들로 최대 몇 명을 처리할 수 있는지가 저장된다.
        # 이게 n보다 작으면 시간을 늘려야함
        if cnt < n:
            start = mid+1
        else: # 반대로 n보다 크다면 최솟값을 찾기 위해 시간을 줄여야함
            end = mid-1
            
    # 반복이 끝나면 start가 답
    return start

